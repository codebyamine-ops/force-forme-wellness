/* --- 3D Wellness Core (Three.js — Section 1) --- */
function initThreeHero() {
  const THREE = window.THREE;
  const canvas = document.getElementById("hero-canvas");
  const heroSection = document.querySelector(".hero");
  if (!THREE || !canvas || !heroSection) return;

  try {
    const scene = new THREE.Scene();

    const camera = new THREE.PerspectiveCamera(
      45,
      heroSection.clientWidth / heroSection.clientHeight,
      0.1,
      100
    );
    camera.position.set(0, 0, 7.5);

    const renderer = new THREE.WebGLRenderer({
      canvas,
      antialias: true,
      alpha: true,
    });
    renderer.setSize(heroSection.clientWidth, heroSection.clientHeight);
    renderer.setPixelRatio(Math.min(window.devicePixelRatio, 2));
    renderer.toneMapping = THREE.ACESFilmicToneMapping;
    renderer.toneMappingExposure = 1.1;

    const ambientLight = new THREE.AmbientLight(0xffffff, 1.3);
    scene.add(ambientLight);

    const goldKeyLight = new THREE.DirectionalLight(0xe6be6a, 2.2);
    goldKeyLight.position.set(4, 5, 5);
    scene.add(goldKeyLight);

    const sageRimLight = new THREE.DirectionalLight(0x6d8f79, 1.5);
    sageRimLight.position.set(-5, -3, 3);
    scene.add(sageRimLight);

    const coreGroup = new THREE.Group();
    scene.add(coreGroup);

    const coreGeo = new THREE.IcosahedronGeometry(1.15, 5);
    const coreMat = new THREE.MeshPhysicalMaterial({
      color: 0xd4a94e,
      roughness: 0.25,
      metalness: 0.35,
      clearcoat: 0.8,
      clearcoatRoughness: 0.15,
    });
    const coreMesh = new THREE.Mesh(coreGeo, coreMat);
    coreGroup.add(coreMesh);

    const posAttr = coreGeo.attributes.position;
    const basePositions = new Float32Array(posAttr.array.length);
    basePositions.set(posAttr.array);

    const ringMat = new THREE.MeshStandardMaterial({
      color: 0x4c6857,
      roughness: 0.4,
      metalness: 0.2,
    });

    const ring1 = new THREE.Mesh(new THREE.TorusGeometry(1.85, 0.018, 24, 120), ringMat);
    ring1.rotation.x = Math.PI * 0.35;
    coreGroup.add(ring1);

    const goldRingMat = new THREE.MeshStandardMaterial({
      color: 0xc69c46,
      roughness: 0.3,
      metalness: 0.5,
    });

    const ring2 = new THREE.Mesh(new THREE.TorusGeometry(2.25, 0.014, 24, 140), goldRingMat);
    ring2.rotation.y = Math.PI * 0.25;
    ring2.rotation.x = -Math.PI * 0.18;
    coreGroup.add(ring2);

    const particleCount = 110;
    const particlePositions = new Float32Array(particleCount * 3);
    for (let i = 0; i < particleCount; i++) {
      const radius = 2.5 + Math.random() * 2.2;
      const theta = Math.random() * Math.PI * 2;
      const phi = Math.acos(2 * Math.random() - 1);

      particlePositions[i * 3] = radius * Math.sin(phi) * Math.cos(theta);
      particlePositions[i * 3 + 1] = radius * Math.sin(phi) * Math.sin(theta);
      particlePositions[i * 3 + 2] = radius * Math.cos(phi);
    }

    const particleGeo = new THREE.BufferGeometry();
    particleGeo.setAttribute("position", new THREE.BufferAttribute(particlePositions, 3));

    const particleMat = new THREE.PointsMaterial({
      color: 0xc69c46,
      size: 0.055,
      transparent: true,
      opacity: 0.75,
    });

    const particles = new THREE.Points(particleGeo, particleMat);
    coreGroup.add(particles);

    function updateLayoutPosition() {
      const isMobile = window.innerWidth <= 820;
      coreGroup.position.set(isMobile ? 0 : 2.15, isMobile ? 1.45 : 0.1, 0);
      coreGroup.scale.setScalar(isMobile ? 0.68 : 1.0);
    }
    updateLayoutPosition();

    const pointer = { x: 0, y: 0, targetX: 0, targetY: 0 };
    window.addEventListener("pointermove", (e) => {
      pointer.targetX = (e.clientX / window.innerWidth) * 2 - 1;
      pointer.targetY = -((e.clientY / window.innerHeight) * 2 - 1);
    });

    window.addEventListener("resize", () => {
      const w = heroSection.clientWidth;
      const h = heroSection.clientHeight;
      camera.aspect = w / h;
      camera.updateProjectionMatrix();
      renderer.setSize(w, h);
      updateLayoutPosition();
    });

    const clock = new THREE.Clock();

    function animate() {
      requestAnimationFrame(animate);
      const elapsed = clock.getElapsedTime();

      pointer.x += (pointer.targetX - pointer.x) * 0.05;
      pointer.y += (pointer.targetY - pointer.y) * 0.05;

      for (let i = 0; i < posAttr.count; i++) {
        const ix = i * 3;
        const bx = basePositions[ix];
        const by = basePositions[ix + 1];
        const bz = basePositions[ix + 2];

        const wave =
          1 +
          0.055 * Math.sin(bx * 2.6 + elapsed * 1.6) * Math.cos(by * 2.6 + elapsed * 1.3) +
          0.03 * Math.sin(bz * 3.2 - elapsed * 1.1);

        posAttr.array[ix] = bx * wave;
        posAttr.array[ix + 1] = by * wave;
        posAttr.array[ix + 2] = bz * wave;
      }
      posAttr.needsUpdate = true;
      coreGeo.computeVertexNormals();

      coreMesh.rotation.y = elapsed * 0.25 + pointer.x * 0.35;
      coreMesh.rotation.x = Math.sin(elapsed * 0.4) * 0.15 - pointer.y * 0.35;

      ring1.rotation.z = elapsed * 0.18;
      ring1.rotation.x = Math.PI * 0.35 + pointer.y * 0.2;

      ring2.rotation.y = Math.PI * 0.25 - elapsed * 0.14;
      ring2.rotation.z = pointer.x * 0.2;

      particles.rotation.y = -elapsed * 0.06;
      particles.rotation.x = pointer.y * 0.1;

      coreGroup.position.y += Math.sin(elapsed * 1.2) * 0.0025;

      renderer.render(scene, camera);
    }

    animate();
  } catch (err) {
    console.warn("3D hero fallback active:", err);
  }
}

initThreeHero();