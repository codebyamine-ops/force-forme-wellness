function slideToCategory(filter, clickedBtn) {
  if (isSlidingCategory) return;
  isSlidingCategory = true;

  document.querySelectorAll(".filter-btn").forEach((b) => {
    b.classList.toggle("active", b === clickedBtn);
  });
  updateFilterSlider();

  const cards = Array.from(document.querySelectorAll(".service-card-wrap"));
  const visibleCards = cards.filter((c) => !c.classList.contains("is-hidden"));

  visibleCards.forEach((c) => {
    c.classList.remove("is-sliding-in");
    c.classList.add("is-sliding-out");
  });

  setTimeout(() => {
    cards.forEach((cardWrap) => {
      cardWrap.classList.remove("is-sliding-out", "is-sliding-in");
      const matches = filter === "all" || cardWrap.dataset.category === filter;
      cardWrap.classList.toggle("is-hidden", !matches);
      if (matches) {
        cardWrap.classList.add("is-visible");
        void cardWrap.offsetWidth;
        cardWrap.classList.add("is-sliding-in");
      }
    });
    isSlidingCategory = false;
  }, 240);
}

